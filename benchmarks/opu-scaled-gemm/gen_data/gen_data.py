"""Data for opu-scaled-gemm: C = sum over k of (sA x A) x (sB x B), P3109.

    gen_data.py <data.S>

M = N = 64 (a 2x2 kernel of 32x32 tiles), K = 96 (three blocks of 32). A and B
are packed for the OPU (k-major); sA holds 64 row scales per block and sB 64
column scales per block, P3109 Binary8p1uf. The expected C rounds to FP32 once
per k step, as OPFMACC.S does, in the kernel's k order. Both 8-bit formats.
"""
import os
import random
import sys
from fractions import Fraction

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "common-data-gen"))

from gfloat import RoundMode  # noqa: E402
from gfloat.formats import format_info_binary32 as FP32  # noqa: E402
from gfloat_ref import FP8_STANDARDS  # noqa: E402
from fma_ref import add, exact, mul, project  # noqa: E402

M, N, K, BLK = 64, 64, 96, 32
RNE = RoundMode.TiesToEven


def scale(code):
    if code == 255:
        return ("nan",)
    return ("num", 0, Fraction(0) if code == 0 else Fraction(2) ** (code - 128))


def arrays(altfmt):
    fi = FP8_STANDARDS["p3109"][f"altfmt{altfmt}"]
    rng = random.Random(altfmt)
    finite = [c for c in range(256) if exact(fi, c)[0] == "num"]
    a = [[rng.choice(finite) for _ in range(M)] for _ in range(K)]
    b = [[rng.choice(finite) for _ in range(N)] for _ in range(K)]
    sa = [[rng.randint(118, 138) for _ in range(M)] for _ in range(K // BLK)]
    sb = [[rng.randint(118, 138) for _ in range(N)] for _ in range(K // BLK)]
    sa[1][5] = 0      # a zero scale: row 5 adds nothing in block 1
    sb[2][40] = 255   # a NaN scale: column 40 is NaN from block 2 on
    c = []
    for i in range(M):
        for j in range(N):
            acc = 0
            for k in range(K):
                blk = k // BLK
                p = mul(mul(scale(sa[blk][i]), exact(fi, a[k][i]), RNE),
                        mul(scale(sb[blk][j]), exact(fi, b[k][j]), RNE), RNE)
                acc = project(FP32, add(p, exact(FP32, acc), RNE), RNE)
            c.append(acc)
    return a, b, sa, sb, c


def emit(f, name, data, kind):
    f.write(f".global {name}\n.balign 64\n{name}:\n")
    per = 32 if kind == "byte" else 8
    for i in range(0, len(data), per):
        f.write(f"    .{kind} " + ", ".join(f"0x{x:0{2 if kind == 'byte' else 8}x}" for x in data[i:i + per]) + "\n")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit("usage: gen_data.py <data.S>")
    with open(sys.argv[1], "w") as f:
        f.write("# Generated by gen_data.py. Do not edit.\n.section .data,\"aw\",@progbits\n")
        for altfmt in (0, 1):
            a, b, sa, sb, c = arrays(altfmt)
            emit(f, f"a{altfmt}", [x for row in a for x in row], "byte")
            emit(f, f"b{altfmt}", [x for row in b for x in row], "byte")
            emit(f, f"sa{altfmt}", [x for row in sa for x in row], "byte")
            emit(f, f"sb{altfmt}", [x for row in sb for x in row], "byte")
            emit(f, f"c{altfmt}", c, "word")
            f.write(f".global out{altfmt}\n.balign 64\nout{altfmt}:\n    .zero {4 * M * N}\n")
