#!/usr/bin/env python3
"""Generate vec-mx-unary/data.S from the gfloat reference model.

Replaces gen_data.c + gen_data.sh, which used Spike as the golden model.

  ./gen_data.py -o ../data.S              # regenerate the checked-in vectors
  ./gen_data.py -n 512 -o ../data.S       # more elements per array
  ./gen_data.py --std p3109 -o ../data.S  # for a P3109 build (also p3109-finite)

Every narrowing array is emitted once per rounding mode, with identical inputs,
so a mismatch isolates the rounding mode rather than the operands.  The array
names (e4m3_*, e5m2_*) match main.c; altfmt selects between the two formats.
"""

import argparse
import os
import signal
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "..", "common-data-gen"))

from gfloat.formats import format_info_binary16, format_info_binary32  # noqa: E402
from gfloat_ref import (  # noqa: E402
    BF16,
    FRM,
    FP8_STANDARDS,
    convert,
    narrowing_inputs,
    print_array,
    print_header,
    print_uint32,
    widening_inputs,
)

FP32 = format_info_binary32
FP16 = format_info_binary16

COUNT = 256


def emit(out, std, count):
    fp8_0 = FP8_STANDARDS[std]["altfmt0"]   # OCP E4M3 or P3109 binary8p4
    fp8_1 = FP8_STANDARDS[std]["altfmt1"]   # OCP E5M2 or P3109 binary8p3

    opt = "" if std == "ocp" else f" --std {std}"
    print_header(out, f"Generated by gen_data.py{opt} (gfloat reference). Do not edit.")
    print_uint32(out, "N", count)

    def narrow(name, src, dst, ssz, dsz, sat=False):
        """One array pair per rounding mode -- rounding is what narrowing exercises.

        The input vectors are identical across modes, so a mismatch isolates the
        rounding mode rather than the operand.
        """
        inp = narrowing_inputs(dst, count, src_fi=src)
        for mode, (_frm, rnd) in FRM.items():
            bits = [convert(src, dst, b, rnd, sat) for b in inp]
            print_array(out, f"{name}_{mode}", "", inp, ssz)
            print_array(out, f"{name}_{mode}", "_out", bits, dsz)

    def widen(name, src, dst, ssz, dsz):
        # Widening is exact -- every source value is representable in the wider
        # format -- so the rounding mode cannot change the result. One array only.
        # 16-bit sources: probe the source's own edges, encoded in the source.
        inp = widening_inputs(src, count) if src.k == 8 else narrowing_inputs(src, count, src_fi=src)
        out_bits = [convert(src, dst, b) for b in inp]
        print_array(out, name, "", inp, ssz)
        print_array(out, name, "_out", out_bits, dsz)

    # IEEE paths, kept so main.c is unchanged.
    narrow("fp16_narrow", FP32, FP16, 4, 2)
    narrow("bf16_narrow", FP32, BF16, 4, 2)

    # BF16 -> 8-bit.  altfmt=1 is the E5M2 slot in main.c.
    narrow("e5m2_narrow", BF16, fp8_1, 2, 1, sat=False)
    narrow("e4m3_narrow", BF16, fp8_0, 2, 1, sat=False)

    # The .sat instruction variant.  Cross-checking against Spike showed the
    # RVV .sat form clamps infinities too, which is gfloat's sat=True.
    narrow("e5m2_narrow_sat", BF16, fp8_1, 2, 1, sat=True)
    narrow("e4m3_narrow_sat", BF16, fp8_0, 2, 1, sat=True)

    widen("fp16_widen", FP16, FP32, 2, 4)
    widen("bf16_widen", BF16, FP32, 2, 4)
    widen("e5m2_widen", fp8_1, BF16, 1, 2)
    widen("e4m3_widen", fp8_0, BF16, 1, 2)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--std", choices=sorted(FP8_STANDARDS), default="ocp",
                    help="8-bit formats of the build (default: ocp)")
    ap.add_argument("-n", "--count", type=int, default=COUNT,
                    help=f"elements per array (default: {COUNT})")
    ap.add_argument("-o", "--output", help="write here instead of stdout")
    args = ap.parse_args()

    out = open(args.output, "w") if args.output else sys.stdout
    try:
        emit(out, args.std, args.count)
    finally:
        if args.output:
            out.close()


if __name__ == "__main__":
    # Writing to a closed pipe (e.g. `gen_data.py | head`) is not an error here.
    signal.signal(signal.SIGPIPE, signal.SIG_DFL)
    main()
