#!/usr/bin/env python3
"""Generate opu-fp8-gemm/data.S from the fma_ref reference model.

  ./gen_data.py --std p3109 -o ../data.S

The checked-in data.S is for OCP FP8 and comes from gen_data.sh (Spike), which
has no P3109. This script writes the same arrays for any standard; for OCP its
inputs differ from Spike's, its answers do not (validate_gemm_ref.py).

C = A x B, M x N x K, accumulated in FP32 one k at a time with
round-to-nearest-even, as OPFMACC does. A is random; B is random or one
special value throughout (+-Inf, NaN, +-0). In P3109, -0 is 0 and both NaNs
are its single NaN; in a format without infinities, Inf is NaN.
"""

import argparse
import math
import os
import random
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "..", "common-data-gen"))

from gfloat import RoundMode, decode_float, encode_float, round_float  # noqa: E402
from gfloat.formats import format_info_binary32 as FP32  # noqa: E402
from fma_ref import add, exact, mul, project  # noqa: E402
from gfloat_ref import FP8_STANDARDS, canonical_nan, print_array, print_header, print_uint32  # noqa: E402

M, N, K = 68, 68, 12
RNE = RoundMode.TiesToEven
# B's contents, in gen_data.c's order
MODES = {"inf": math.inf, "ninf": -math.inf, "nan": math.nan, "nnan": -math.nan,
         "zero": 0.0, "nzero": -0.0, "rand": None}


def special(fi, v):
    """v's code; a NaN keeps v's sign where the format has a negative NaN."""
    r = v if math.isnan(v) else round_float(fi, v, rnd=RNE)
    if math.isnan(r):
        return canonical_nan(fi) | (0x80 if math.copysign(1, v) < 0 else 0)
    return encode_float(fi, r)


def finite_codes(fi):
    return [c for c in range(256) if math.isfinite(decode_float(fi, c).fval)]


def gemm(fi, at, b):
    """C[i][j], row-major, from A transposed (K x M) and B (K x N)."""
    c = []
    for i in range(M):
        for j in range(N):
            acc = 0
            for k in range(K):
                p = mul(exact(fi, at[k * M + i]), exact(fi, b[k * N + j]), RNE)
                acc = project(FP32, add(p, exact(FP32, acc), RNE), RNE)
            c.append(acc)
    return c


def emit(out, std):
    print_header(out, f"Generated by gen_data.py --std {std} (fma_ref reference). Do not edit.")
    for name, v in (("M", M), ("N", N), ("K", K)):
        print_uint32(out, name, v)
    rng = random.Random(0)
    for mode, v in MODES.items():
        for fname in ("e4m3", "e5m2"):
            fi = FP8_STANDARDS[std]["altfmt0" if fname == "e4m3" else "altfmt1"]
            codes = finite_codes(fi)
            at = [rng.choice(codes) for _ in range(K * M)]
            b = [rng.choice(codes) for _ in range(K * N)] if v is None else [special(fi, v)] * (K * N)
            name = f"{fname}_rand_{mode}"
            print_array(out, name, "_at", at, 1)
            print_array(out, name, "_b", b, 1)
            print_array(out, name, "_c", gemm(fi, at, b), 4)
            out.write(f".global {name}_out\n.balign 64\n{name}_out:\n    .space {M * N * 4}\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--std", choices=sorted(FP8_STANDARDS), required=True, help="8-bit formats of the build")
    ap.add_argument("-o", "--output", help="write here instead of stdout")
    args = ap.parse_args()
    out = open(args.output, "w") if args.output else sys.stdout
    try:
        emit(out, args.std)
    finally:
        if args.output:
            out.close()


if __name__ == "__main__":
    main()
